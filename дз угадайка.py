# Задаём константу точности (чем меньше число, тем выше точность)
# 0.0000001 означает точность до 7-го знака после запятой
EPSILON = 0.0000001


# Функция проверки: угадали ли мы число с учётом точности
def is_correct(guess, secret):
    # Проверяем, насколько наше предположение близко к загаданному числу.
    # Если разница меньше нашей точности — значит, мы угадали.
    if abs(guess - secret) < EPSILON:
        return True
    return False


# Основная функция бинарного поиска для действительных чисел
def guess_number(secret):
    # Нижняя граница диапазона (минимум -10^9)
    low = -(10.0**9)
    # Верхняя граница диапазона (максимум 10^9)
    high = 10.0**9

    # Цикл работает до тех пор, пока разница между границами больше точности
    while high - low > EPSILON:

        # Находим середину диапазона (обычное деление, даёт float)
        mid = (low + high) / 2

        # Проверяем, угадали ли мы число с нужной точностью
        if is_correct(mid, secret):
            # Если да — возвращаем середину
            return mid
        # Если наше число меньше загаданного
        elif mid < secret:
            # Сдвигаем нижнюю границу вправо (без +1, так как работаем с float)
            low = mid
        # Если наше число больше загаданного
        else:
            # Сдвигаем верхнюю границу влево (без -1)
            high = mid

    # Если цикл закончился, возвращаем середину последнего диапазона
    # (она гарантированно попадает в нужную точность)
    return (low + high) / 2


# Загадываем дробное число для теста
secret_number = float(input())

# Вызываем функцию угадывания
result = guess_number(secret_number)

# Выводим результат. :.7f означает вывод с 7 знаками после запятой
print(f"Загаданное число: {secret_number:.7f}")
print(f"Найденное число:  {result:.7f}")
